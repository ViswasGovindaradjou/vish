class MovieTicket:
    def __init__(self, booked):
        self.booked = booked

    def is_booked(self, seat):
        return seat in self.booked

    def total_booked(self):
        return len(self.booked)

    def available_seats(self):
        return [i for i in range(1, 21) if i not in self.booked]


