class ShoppingCart:
    def __init__(self, prices):
        self.prices = prices

    def total_bill(self):
        return sum(self.prices)

    def costliest_item(self):
        return max(self.prices)

    def discounted_bill(self):
        total = self.total_bill()
        if total > 5000:
            total *= 0.85
        return total


