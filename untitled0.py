def is_prime(n):
    if n < 2:
        return False
    for i in range(2, n):
        if n % i == 0:
            return False
    return True

def is_circular_prime(n):
    s = str(n)
    for i in range(len(s)):
        r = int(s[i:] + s[:i])  # rotation
        if not is_prime(r):
            return False
    return True

n = int(input("Enter number: "))

if is_circular_prime(n):
    print("Circular Prime")
else:
    print("Not Circular Prime")



